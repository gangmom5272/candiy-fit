"""가드를 통과한 약 일반 지식 질문의 답에서 약을 쓰는 방법을 말한 문장을 찾는다.

이 경로의 답은 약의 분류와 차이(처방이 필요한지 포함)와 상담 안내만 말하면 된다. 그래서 새는 표현을 하나씩 찾는 대신
약을 쓰는 행동의 동사, 양·횟수·때·괜찮다는 판단의 말, 효과 장담·추천·피하라는 말이 든 문장을 약을 가리키는 말이
없어도 모두 찾는다. 판단을 상담에 미루는 문장("먹어도 되는지는 의사나 약사와 상담해 주세요")만 뺀다. 생활 습관
문장이나 약의 작용을 설명하는 문장도 걸릴 수 있지만, 걸리면 고정 답이 나가 새는 답보다 안전하다.
숫자와 용량 단위는 답 어디에 있든 찾고, 흔한 제품명·성분명 몇 개는 보조로만 둔다. 목록은 이 파일과 테스트에만
둔다. "졸음이 오는 성분" 같은 일반 설명과 멜라토닌은 찾지 않는다.
"""

from __future__ import annotations

import re
from typing import Literal

LeakKind = Literal["dose", "advice", "name"]

_COUNT_UNIT = r"알(?!려|아|고|았|면|게|지)|캡슐|방울|포(?!함|기|인트)"
_TABLET_UNIT = r"정(?!도|상|말|리|확|해|하|거)"
_DOSE = re.compile(
    r"\d+(?:[.,]\d+)?\s?(?:mg|㎎|밀리그램|밀리그람|밀리(?!그|리|미|초)|mcg|㎍|μg|마이크로그램|g(?![a-z])|그램"
    rf"|ml|㎖|밀리리터|cc|iu|{_TABLET_UNIT}|{_COUNT_UNIT})"
    rf"|(?:한|두|세|네|반)\s?(?:{_COUNT_UNIT})|(?:한|두|세|네|반)\s{_TABLET_UNIT}"
    r"|(?:하루|1일|매일|한\s?번에)\s?(?:에\s?)?(?:\d+|한|두|세|네)\s?(?:번|회|알|정|캡슐|포)"
    r"\s?(?:씩\s?)?(?:정도\s?)?(?:먹|드|복용|섭취|까지|이상|이내|넘지|넘게|초과)"
    r"|(?:복용량|투여량|용량)[^.?!\n]{0,12}\d",
    re.IGNORECASE,
)
# 약을 쓰는 행동을 가리키는 동사와 그 활용. 약을 가리키는 말이 없어도 이 동사가 든 문장은 약을 쓰는 방법을 말한
# 것으로 본다 ("통증을 줄이는 약"처럼 약의 작용을 말한 문장도 걸린다)
_USE_VERB = re.compile(
    r"먹|드시|드셔|드세|드실|드신|복용|섭취|투여|투약|사용"
    r"|쓰(?:는|면|고|지|세|셔|시|기|던|을|려|게|자|니|며|도|나)|써|쓴|쓸"
    r"|끊|그만\s?두|그만\s?둬|줄이|줄여|줄인|늘리|늘려|늘린|넘기|넘겨|조절|피하|피해|피할|삼가|챙기|챙겨"
    r"|건너\s?뛰|건너\s?뛴|건너\s?뛸|보관"
)
# 판단을 상담에 미루는 문장. 이 문장의 동사는 약을 쓰는 방법이 아니라 상담할 내용이다
_DEFER = re.compile(
    r"되는지|될지|할지|하는지|괜찮은지|좋은지|맞는지|여부|판단"
    r"|안내해\s?드릴\s?수\s?없|안내할\s?수\s?없|알려\s?드릴\s?수\s?없|말씀드릴\s?수\s?없"
)
# 문장 어디에 있든 먹으라거나 먹지 말라는 말 (상담 문장에 섞여 있어도 새는 답이다)
_ADVICE = re.compile(
    r"(?:먹|드시|드셔|드실|복용|섭취|투여)[가-힣]{0,3}?\s?"
    r"(?:세요|십시오|보세요|봐요|볼\s?만|보는\s?(?:것도|게)|보시는\s?(?:것도|게)|보셔도"
    r"|도\s?(?:크게\s?|별\s?)?(?:돼|됩|괜찮|좋|무방|상관\s?없|문제|지장|나쁘지)"
    r"|면\s?(?:돼|됩|좋|도움|괜찮|충분)"
    r"|(?:는|시는)\s?(?:게|것이|건|걸|것도)\s?(?:좋|괜찮|나|맞|방법|일반적|보통|무난|안전)"
    r"|(?:기를|길|시기를|시길|는\s?걸|시는\s?걸|는\s?것을|시는\s?것을)\s?(?:추천|권)"
    r"|을?\s?만\s?(?:해|합|하)"
    r"|지\s?(?:마세요|마십시오|말아|말고|않는\s?(?:게|것이|편이)\s?좋|않으시는\s?(?:게|것이)\s?좋|않도록)"
    r"|면\s?안\s?(?:돼|됩))"
    r"|드세요|드십시오"
    r"|써\s?(?:보세요|봐요|보는\s?(?:것도|게)|보셔도|도\s?(?:돼|됩|괜찮|좋))"
    r"|쓰(?:세요|셔도|시면\s?(?:돼|됩|좋)|(?:는|시는)\s?(?:게|것이|건)\s?(?:좋|괜찮|나)"
    r"|지\s?(?:마세요|말아|않는\s?(?:게|것이)\s?좋))"
    r"|끊(?:으세요|으셔도|어도\s?(?:돼|괜찮|좋))|중단(?:하세요|하셔도|해도\s?(?:돼|괜찮))"
    r"|줄이세요|줄여도\s?(?:돼|괜찮)|늘리세요|늘려도\s?(?:돼|괜찮)"
    r"|끊(?:을|으)[^.?!\n]{0,12}(?:줄이|줄여)"
    r"|많이\s?(?:써요|쓰여요|쓰는\s?(?:약|편))|잘\s?(?:들어요|들어서|듣는\s?편|들었)"
)
# 효과를 장담하거나, 약을 권하거나 고르거나, 먹지 말라고 하는 말. 약을 가리키는 말이 없어도 찾는다
_DRUG_ADVICE = re.compile(
    r"도움이\s?(?:될|돼|됩|되)|효과가\s?(?:있|좋|빠르|빨라|커|크|확실)|효과를\s?(?:볼|보)|효과적"
    r"|안전(?:한\s?편|해요|합니다|하다)|무난|괜찮(?:아|습|은\s?(?:선택|방법|편))"
    r"|좋은\s?(?:선택|방법)|(?:데|에)\s?좋(?:아|습)|부터(?:요|\s?(?:시작|드|써|복용))"
    r"|보다(?:는)?[^.?!\n]{0,20}?(?:나아|낫|좋아|좋습|안전|효과)"
    r"|피하(?:세요|시는\s?게|는\s?게)|자제하(?:세요|시는\s?게|는\s?게)|삼가(?:세요|시는\s?게|는\s?게)"
    r"|(?:조금씩|천천히|서서히|점점|양을|용량을|복용량을)\s?(?:줄이|줄여|늘리|늘려)|끊으면|끊을\s?때|중단하면|중단할\s?때"
    r"|추천(?:해요|합니다|드려요|드립니다|할게요|해\s?드려요|해\s?드릴게요)"
    r"|권(?:해요|합니다|해\s?드려요|해\s?드립니다|장해요|장합니다|장돼요)"
)
# 동사 없이 양·횟수·때·판단만 말한 문장("한 알이면 충분해요")을 찾는 보조 검사다. 양은 숫자나 한·반·두에 약
# 단위가 붙은 표현("개"는 숫자와 붙을 때만), 횟수는 기간과 숫자가 붙은 표현, 때는 먹는 때, 판단은 충분·안전을
# 장담하는 말이다. "하나"·"한 번"처럼 단위 없는 말과 "매일"·"가끔"·"계속" 같은 넓은 낱말은 넣지 않는다
_AMOUNT_OR_TIME = re.compile(
    r"(?:\d+(?:[.,]\d+)?)\s?(?:알(?!려|아|고|았|면|게|지)|정(?!도|상|말|리|확|해|하|거)|포(?!함|기|인트)|캡슐|개(?!월)|mg|㎎)"
    r"|(?:한|두|세|네|반|한두|두세)\s?(?:알(?!려|아|고|았|면|게|지)|포(?!함|기)|캡슐)"
    r"|(?:한|두|세|네|반)\s정(?!도|상|말|리|확|해|하|거|된|되|적|제)"
    r"|(?:하루|1일|주|일주일|이틀|사흘|한\s?달)\s?(?:에\s?)?(?:\d+|한|두|세|네|다섯|몇)\s?(?:번|회)"
    r"|\d+\s?회|\d+\s?(?:일|주)\s?(?:이상|이내|넘게|넘지|까지|동안|만|간|째)|\d+\s?(?:분|시간)\s?(?:간격|마다)"
    r"|자기\s?전|잠들기\s?전|취침\s?전|식사\s?(?:직)?(?:후|전)|식후|식전|공복|빈속|필요할\s?때"
    r"|충분|괜찮|문제\s?(?:가\s?|는\s?)?없|무리(?:가|는)?\s?없|걱정(?:할)?\s?(?:건|것은|거|은|이)?\s?없",
    re.IGNORECASE,
)
# 흔한 제품명·성분명 (보조)
_NAMES = re.compile(
    r"졸피뎀|독시라민|디펜히드라민|디펜하이드라민|트리아졸람|알프라졸람|로라제팜|스틸녹스|아세트아미노펜|이부프로펜|타이레놀"
    r"|zolpidem|doxylamine|diphenhydramine|acetaminophen|ibuprofen",
    re.IGNORECASE,
)
# 문장. 소수점(0.5)에서는 나누지 않는다
_SENTENCE = re.compile(r"(?:[^.?!\n]|\.(?=\d))+")


def _advises(answer: str) -> bool:
    if _ADVICE.search(answer):
        return True
    for m in _SENTENCE.finditer(answer):
        sentence = m.group()
        if _DEFER.search(sentence):
            continue
        if _USE_VERB.search(sentence) or _AMOUNT_OR_TIME.search(sentence) or _DRUG_ADVICE.search(sentence):
            return True
    return False


def find_leak(answer: str) -> LeakKind | None:
    """복용 판단이 새는 표현의 종류. 없으면 None 이다."""
    if _DOSE.search(answer):
        return "dose"
    if _advises(answer):
        return "advice"
    if _NAMES.search(answer):
        return "name"
    return None
