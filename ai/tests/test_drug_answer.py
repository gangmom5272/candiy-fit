# 보조 검사: 동사 없이 양·횟수·때·판단만 말한 문장. 양은 숫자나 한·반·두와 약 단위, 횟수는 기간과 숫자가 붙은 표현,
# 때는 먹는 때, 판단은 충분·안전을 장담하는 말이다
@pytest.mark.parametrize(
    "answer",
    [
        "보통은 반 알이면 돼요.",
        "영양제는 하루 두 번이 보통이에요.",
        "감기약은 3일 넘게 이어 가지 않는 편이에요.",
        "해열제는 4시간 간격이 일반적이에요.",
        "수면 유도제는 취침 전이 보통이에요.",
        "공복만 아니면 문제없어요.",
        "이 정도는 괜찮은 편이에요.",
        "필요할 때 하나 더 있어도 걱정 없어요.",
        "처음엔 하루에 한 번만 해 보세요.",
        "보통은 이틀에 한 번이면 충분해요.",
        "젤리는 하루 2개가 보통이에요.",
    ],
)
def test_amount_or_time_words_are_found(answer):
    # 약 단위가 붙은 양은 용량 표현 검사에도 걸려 종류가 dose 일 수 있다
    assert find_leak(answer) is not None


