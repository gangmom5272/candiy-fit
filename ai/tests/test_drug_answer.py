        "수면제는 의존이 생길 수 있어 의사의 처방에 따라 쓰는 약이에요.",
        "한정된 기간에만 쓰는 약도 있어요.",
        "약 없이도 잠드는 습관을 바꾸면 도움이 될 수 있어요.",
        "규칙적인 운동이 잠드는 데 도움이 될 수 있어요.",
        "수면 유도제가 궁금하면 약사에게 물어봐도 괜찮아요.",
